const end: Node = { n: 'endMove' };
const g = (o: Omit<Extract<Node, { n: 'gain' }>, 'n'>): Node => ({ n: 'gain', ...o });
const gold = (x: number): Node => g({ gold: x });
const lose = (crosses: number): Node => ({ n: 'lose', crosses });
const anger = (add: number): Node => ({ n: 'hostilityNearest', add });
const europe = (skull = false): Node => ({ n: 'toEurope', ...(skull ? { skull: true } : {}) });
const go = (x = 1): Node => ({ n: 'moves', add: x });
const roll = (...t: [number, Node[]][]): Node => ({ n: 'roll', table: t.map(([max, d]) => ({ max, do: d })) });
const opt = (id: string, en: string, ru: string, d: Node[], cost?: Cost, needs?: ChoiceOption['needs']): ChoiceOption =>
  ({ id, en, ru, do: d, ...(cost ? { cost } : {}), ...(needs ? { needs } : {}) });
const choose = (id: string, ...options: ChoiceOption[]): Node => ({ n: 'choice', id, options });
const leave = (en = 'Move on', ru = 'Продолжить путь') => opt('leave', en, ru, [go()]);

